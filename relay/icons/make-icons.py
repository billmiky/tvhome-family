# Draws the phone web app's icon (a TV on an orange tile) and writes src/icons.js with the PNGs inlined.
# Run: python3 icons/make-icons.py
import base64, io, os
from PIL import Image, ImageDraw

S = 1024
here = os.path.dirname(os.path.abspath(__file__))

def tile():
    img = Image.new("RGB", (S, S))
    top, bottom = (255, 176, 32), (255, 106, 0)
    d = ImageDraw.Draw(img)
    for y in range(S):
        t = y / (S - 1)
        d.line([(0, y), (S, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(top, bottom)))
    d = ImageDraw.Draw(img)
    w = (255, 255, 255)
    # Everything inside the maskable safe zone (the middle 80%).
    # Antenna
    d.line([(512, 330), (420, 236)], fill=w, width=34)
    d.line([(512, 330), (604, 236)], fill=w, width=34)
    for x in (420, 604):
        d.ellipse([x - 26, 236 - 26, x + 26, 236 + 26], fill=w)
    # Body and screen
    d.rounded_rectangle([222, 320, 802, 724], radius=70, fill=w)
    d.rounded_rectangle([272, 368, 752, 676], radius=36, fill=(28, 28, 34))
    # A glint on the screen
    d.rounded_rectangle([308, 404, 420, 432], radius=14, fill=(70, 70, 82))
    # Stand
    d.rounded_rectangle([392, 760, 632, 800], radius=20, fill=w)
    d.rectangle([494, 724, 530, 770], fill=w)
    return img

big = tile()
out = {}
for name, px in (("icon512", 512), ("icon192", 192), ("apple180", 180)):
    b = io.BytesIO()
    big.resize((px, px), Image.LANCZOS).save(b, "PNG", optimize=True)
    out[name] = base64.b64encode(b.getvalue()).decode()
    big.resize((px, px), Image.LANCZOS).save(os.path.join(here, name + ".png"))

with open(os.path.join(here, "..", "src", "icons.js"), "w") as f:
    f.write("// Generated by icons/make-icons.py: the web app icons as base64 PNG.\n")
    for k, v in out.items():
        f.write(f'export const {k.upper()} = "{v}";\n')
print({k: len(v) for k, v in out.items()})
